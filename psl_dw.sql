INSERT INTO psl_dw.dim_match (match_id, season, event_name, match_number, stage, team1, team2,
       toss_winner, toss_decision, winner, win_by_type, win_by_value, result, method,
       eliminator, player_of_match, umpire1, umpire2)
SELECT TRIM(match_id),
       TRIM(season),
       TRIM(event_name),
       match_number::SMALLINT,
       COALESCE(NULLIF(TRIM(stage), ''), 'Not Applicable'),
       TRIM(team1),
       TRIM(team2),
       TRIM(toss_winner),
       TRIM(toss_decision),
       COALESCE(NULLIF(TRIM(winner), ''), 'Not Applicable'),
       COALESCE(NULLIF(TRIM(win_by_type), ''), 'Not Applicable'),
       win_by_value::SMALLINT,
       COALESCE(NULLIF(TRIM(result), ''), 'Not Applicable'),
       COALESCE(NULLIF(TRIM(method), ''), 'Not Applicable'),
       COALESCE(NULLIF(TRIM(eliminator), ''), 'Not Applicable'),
       COALESCE(NULLIF(REGEXP_REPLACE(TRIM(player_of_match), ' \(\d+\)', '', 'g'), ''), 'Not Applicable'),
       COALESCE(NULLIF(TRIM(umpire1), ''), 'Not Applicable'),
