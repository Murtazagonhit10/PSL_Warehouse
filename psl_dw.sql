-- and the source business key is kept as UNIQUE)
--   dim_team              8 rows    one per franchise
--   dim_venue             7 rows    names and cities cleaned through map_venue
--   dim_innings           4 rows    innings 1-2, super over innings 3-4
--   dim_over              20 rows   over 1-20 with phase (Powerplay 1-6,
--                                   Middle 7-15, Death 16-20)
--   dim_dismissal_type    11 rows   10 kinds + key -1 Not Applicable
--                                   (retired hurt is not a wicket)
--   dim_extra_type        8 rows    7 types + key -1 Not Applicable
--   dim_date              4,018     every day from 2016-01-01 to 2026-12-31
--   dim_player            461 rows  460 players + key -1 Not Applicable
--                                   (one row per player_id; " (n)" removed from names)
--   dim_match             357 rows  empty text stored as 'Not Applicable';
--                                   win_by_type widened to VARCHAR(20)
--
-- FACT TABLES (primary key = grain, foreign keys to every dimension,
-- NOT NULL keys, CHECK rules on runs and 0/1 flags)
--   fact_match_player     7,858     one row per player in a team's XI (factless)
--   fact_over_snapshot    13,594    one row per over per innings per match
--   fact_delivery         83,799    one row per delivery entry
--   Business keys are replaced by surrogate keys through joins.
--   Balls without a wicket or extras point to the -1 rows, so no key is NULL.
--   Player names in deliveries are looked up by (match_id, name) to get player_id.
--
-- VALIDATION RESULTS
--   Row counts: every fact table has the same number of rows as its staging table.
--   Runs: 115,022 in stg_deliveries, fact_delivery and fact_over_snapshot.
--   Wickets: 4,503 in stg_deliveries and fact_delivery.
--   dim_match: 313 league matches, 4 ties, 3 no results, 4 D/L matches,
--              no bracket numbers left in player_of_match.
--   No player name is repeated inside a match, so the lookup is unambiguous.
--   Every load uses ON CONFLICT DO NOTHING, so reruns do not create duplicates.
