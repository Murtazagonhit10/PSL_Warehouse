-- load dim_venue. The venue names come through map_venue
INSERT INTO psl_dw.dim_venue (venue_name, city)
SELECT DISTINCT v.venue_clean, v.city_clean
FROM psl_staging.stg_matches m
JOIN psl_staging.map_venue v ON v.venue_raw = m.venue
ORDER BY 1
ON CONFLICT (venue_name) DO NOTHING;

-- check
SELECT venue_key, venue_name, city FROM psl_dw.dim_venue ORDER BY venue_key;







-- load dim_innings. This is the small table of innings numbers. The values come from the ball-by-ball data.
INSERT INTO psl_dw.dim_innings (innings_no, is_super_over, innings_label)
SELECT DISTINCT
       innings_no::SMALLINT,
       is_super_over = '1',
       CASE innings_no::INT
            WHEN 1 THEN 'First innings'
            WHEN 2 THEN 'Second innings'
            WHEN 3 THEN 'Super over - first innings'
            WHEN 4 THEN 'Super over - second innings'
            ELSE 'Extra innings'
       END
FROM psl_staging.stg_deliveries
ORDER BY 1
ON CONFLICT (innings_no) DO NOTHING;

-- check
SELECT innings_key, innings_no, is_super_over, innings_label
FROM psl_dw.dim_innings ORDER BY innings_key;






-- load dim_over. The over numbers come from the delivery data

INSERT INTO psl_dw.dim_over (over_no, over_number, phase)
SELECT DISTINCT
       over_no::SMALLINT,
       over_no::SMALLINT + 1,
       CASE WHEN over_no::INT <= 5  THEN 'Powerplay'
            WHEN over_no::INT <= 14 THEN 'Middle'
            ELSE 'Death'
       END
FROM psl_staging.stg_deliveries
ORDER BY 1
ON CONFLICT (over_no) DO NOTHING;

-- check
SELECT phase, MIN(over_number) AS first_over, MAX(over_number) AS last_over, COUNT(*) AS overs
FROM psl_dw.dim_over
GROUP BY phase
ORDER BY first_over;







-- load dim_dismissal_type. This one has two parts.
INSERT INTO psl_dw.dim_dismissal_type (dismissal_type_key, dismissal_kind, counts_as_wicket, credited_to_bowler)
VALUES (-1, 'Not Applicable', FALSE, FALSE)
ON CONFLICT (dismissal_type_key) DO NOTHING;

INSERT INTO psl_dw.dim_dismissal_type (dismissal_kind, counts_as_wicket, credited_to_bowler)
SELECT DISTINCT
       TRIM(dismissal_kind),
       TRIM(dismissal_kind) <> 'retired hurt',
       TRIM(dismissal_kind) IN ('bowled', 'caught', 'caught and bowled', 'lbw', 'stumped', 'hit wicket')
FROM psl_staging.stg_deliveries
WHERE dismissal_kind IS NOT NULL
ORDER BY 1
ON CONFLICT (dismissal_kind) DO NOTHING;


-- check
SELECT dismissal_type_key, dismissal_kind, counts_as_wicket, credited_to_bowler
FROM psl_dw.dim_dismissal_type ORDER BY dismissal_type_key;





-- load dim_extra_type. Same pattern: a “Not Applicable” row with key -1 for balls with no extras
INSERT INTO psl_dw.dim_extra_type (extra_type_key, extra_type, is_wide, is_noball, is_bye, is_legbye, is_penalty)
VALUES (-1, 'Not Applicable', FALSE, FALSE, FALSE, FALSE, FALSE)
ON CONFLICT (extra_type_key) DO NOTHING;

INSERT INTO psl_dw.dim_extra_type (extra_type, is_wide, is_noball, is_bye, is_legbye, is_penalty)
SELECT DISTINCT
       TRIM(extras_type),
       'wides'   = ANY (STRING_TO_ARRAY(TRIM(extras_type), ';')),
       'noballs' = ANY (STRING_TO_ARRAY(TRIM(extras_type), ';')),
       'byes'    = ANY (STRING_TO_ARRAY(TRIM(extras_type), ';')),
       'legbyes' = ANY (STRING_TO_ARRAY(TRIM(extras_type), ';')),
       'penalty' = ANY (STRING_TO_ARRAY(TRIM(extras_type), ';'))
FROM psl_staging.stg_deliveries
WHERE extras_type IS NOT NULL
ORDER BY 1
ON CONFLICT (extra_type) DO NOTHING;


-- check
SELECT extra_type_key, extra_type, is_wide, is_noball, is_bye, is_legbye, is_penalty
FROM psl_dw.dim_extra_type ORDER BY extra_type_key;







-- load dim_date. This is the calendar table. We don’t read it from a file. We generate a row for every day 
-- from 1 January of the first match year to 31 December of the last match year
INSERT INTO psl_dw.dim_date
SELECT TO_CHAR(d, 'YYYYMMDD')::INT,
       d::DATE,
       EXTRACT(DAY FROM d)::SMALLINT,
       TRIM(TO_CHAR(d, 'Day')),
       EXTRACT(ISODOW FROM d)::SMALLINT,
       EXTRACT(ISODOW FROM d) IN (6, 7),
       EXTRACT(MONTH FROM d)::SMALLINT,
       TRIM(TO_CHAR(d, 'Month')),
       EXTRACT(QUARTER FROM d)::SMALLINT,
       EXTRACT(YEAR FROM d)::SMALLINT
FROM GENERATE_SERIES(
         (SELECT MAKE_DATE(EXTRACT(YEAR FROM MIN(match_date::DATE))::INT, 1, 1) FROM psl_staging.stg_matches),
         (SELECT MAKE_DATE(EXTRACT(YEAR FROM MAX(match_date::DATE))::INT, 12, 31) FROM psl_staging.stg_matches),
         INTERVAL '1 day') AS g(d)
ON CONFLICT (date_key) DO NOTHING;


-- check

SELECT COUNT(*) AS days, MIN(full_date) AS first_day, MAX(full_date) AS last_day FROM psl_dw.dim_date;

SELECT COUNT(*) AS match_dates_missing
FROM psl_staging.stg_matches m
LEFT JOIN psl_dw.dim_date dd ON dd.full_date = m.match_date::DATE
WHERE dd.date_key IS NULL;






