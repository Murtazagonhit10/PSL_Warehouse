
-- PSL DW sql file that comes after staging

CREATE SCHEMA IF NOT EXISTS psl_dw;

-- Creating Dimension tables
DROP TABLE IF EXISTS psl_dw.dim_date CASCADE;
CREATE TABLE psl_dw.dim_date (
    date_key       INT          PRIMARY KEY,
    full_date      DATE         NOT NULL UNIQUE,
    day_of_month   SMALLINT     NOT NULL,
    day_name       VARCHAR(10)  NOT NULL,
    day_of_week_no SMALLINT     NOT NULL,
    is_weekend     BOOLEAN      NOT NULL,
    month_no       SMALLINT     NOT NULL,
    month_name     VARCHAR(10)  NOT NULL,
    quarter_no     SMALLINT     NOT NULL,
    year           SMALLINT     NOT NULL
);

DROP TABLE IF EXISTS psl_dw.dim_match CASCADE;
CREATE TABLE psl_dw.dim_match (
    match_key       INT          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    match_id        VARCHAR(20)  NOT NULL UNIQUE,
    season          VARCHAR(10)  NOT NULL,
    event_name      VARCHAR(80)  NOT NULL,
    match_number    SMALLINT,
    stage           VARCHAR(30)  NOT NULL,
    team1           VARCHAR(60)  NOT NULL,
    team2           VARCHAR(60)  NOT NULL,
    toss_winner     VARCHAR(60)  NOT NULL,
    toss_decision   VARCHAR(10)  NOT NULL,
    winner          VARCHAR(60)  NOT NULL,
    win_by_type     VARCHAR(10)  NOT NULL,
    win_by_value    SMALLINT,
    result          VARCHAR(20)  NOT NULL,
    method          VARCHAR(20)  NOT NULL,
    eliminator      VARCHAR(60)  NOT NULL,
    player_of_match VARCHAR(100) NOT NULL,
    umpire1         VARCHAR(60)  NOT NULL,
    umpire2         VARCHAR(60)  NOT NULL
);

DROP TABLE IF EXISTS psl_dw.dim_venue CASCADE;
CREATE TABLE psl_dw.dim_venue (
    venue_key   INT          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    venue_name  VARCHAR(120) NOT NULL UNIQUE,
    city        VARCHAR(60)  NOT NULL
);

DROP TABLE IF EXISTS psl_dw.dim_team CASCADE;
CREATE TABLE psl_dw.dim_team (
    team_key    INT          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    team_name   VARCHAR(60)  NOT NULL UNIQUE
);

DROP TABLE IF EXISTS psl_dw.dim_player CASCADE;
CREATE TABLE psl_dw.dim_player (
    player_key  INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id   VARCHAR(12)  NOT NULL UNIQUE,
    player_name VARCHAR(80)  NOT NULL
);

DROP TABLE IF EXISTS psl_dw.dim_innings CASCADE;
CREATE TABLE psl_dw.dim_innings (
    innings_key   SMALLINT     GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    innings_no    SMALLINT     NOT NULL UNIQUE,
    is_super_over BOOLEAN      NOT NULL,
    innings_label VARCHAR(30)  NOT NULL
);

DROP TABLE IF EXISTS psl_dw.dim_over CASCADE;
CREATE TABLE psl_dw.dim_over (
    over_key    SMALLINT     GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    over_no     SMALLINT     NOT NULL UNIQUE,
    over_number SMALLINT     NOT NULL,
    phase       VARCHAR(12)  NOT NULL
);

DROP TABLE IF EXISTS psl_dw.dim_dismissal_type CASCADE;
CREATE TABLE psl_dw.dim_dismissal_type (
    dismissal_type_key SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dismissal_kind     VARCHAR(30) NOT NULL UNIQUE,
    counts_as_wicket   BOOLEAN     NOT NULL,
    credited_to_bowler BOOLEAN     NOT NULL
);

DROP TABLE IF EXISTS psl_dw.dim_extra_type CASCADE;
CREATE TABLE psl_dw.dim_extra_type (
    extra_type_key SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extra_type     VARCHAR(40) NOT NULL UNIQUE,
    is_wide        BOOLEAN     NOT NULL,
    is_noball      BOOLEAN     NOT NULL,
    is_bye         BOOLEAN     NOT NULL,
    is_legbye      BOOLEAN     NOT NULL,
    is_penalty     BOOLEAN     NOT NULL
);






