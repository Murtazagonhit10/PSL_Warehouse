DROP TABLE IF EXISTS psl_dw.fact_delivery CASCADE;
CREATE TABLE psl_dw.fact_delivery (
    match_key            INT      NOT NULL REFERENCES psl_dw.dim_match (match_key),
    innings_key          SMALLINT NOT NULL REFERENCES psl_dw.dim_innings (innings_key),
    delivery_seq         SMALLINT NOT NULL,
    date_key             INT      NOT NULL REFERENCES psl_dw.dim_date (date_key),
    venue_key            INT      NOT NULL REFERENCES psl_dw.dim_venue (venue_key),
    over_key             SMALLINT NOT NULL REFERENCES psl_dw.dim_over (over_key),
    batting_team_key     INT      NOT NULL REFERENCES psl_dw.dim_team (team_key),
    bowling_team_key     INT      NOT NULL REFERENCES psl_dw.dim_team (team_key),
    batter_key           INT      NOT NULL REFERENCES psl_dw.dim_player (player_key),
    bowler_key           INT      NOT NULL REFERENCES psl_dw.dim_player (player_key),
    non_striker_key      INT      NOT NULL REFERENCES psl_dw.dim_player (player_key),
    dismissed_player_key INT      NOT NULL REFERENCES psl_dw.dim_player (player_key),
    dismissal_type_key   SMALLINT NOT NULL REFERENCES psl_dw.dim_dismissal_type (dismissal_type_key),
    extra_type_key       SMALLINT NOT NULL REFERENCES psl_dw.dim_extra_type (extra_type_key),
    runs_batter          SMALLINT NOT NULL CHECK (runs_batter >= 0),
    runs_extras          SMALLINT NOT NULL CHECK (runs_extras >= 0),
    runs_total           SMALLINT NOT NULL CHECK (runs_total >= 0),
    runs_conceded        SMALLINT NOT NULL CHECK (runs_conceded >= 0),
    is_legal_ball        SMALLINT NOT NULL CHECK (is_legal_ball IN (0, 1)),
    balls_faced          SMALLINT NOT NULL CHECK (balls_faced IN (0, 1)),
    wicket_count         SMALLINT NOT NULL CHECK (wicket_count >= 0),
    is_dot_ball          SMALLINT NOT NULL CHECK (is_dot_ball IN (0, 1)),
    PRIMARY KEY (match_key, innings_key, delivery_seq)
);

DROP TABLE IF EXISTS psl_dw.fact_over_snapshot CASCADE;
CREATE TABLE psl_dw.fact_over_snapshot (
    match_key              INT      NOT NULL REFERENCES psl_dw.dim_match (match_key),
    innings_key            SMALLINT NOT NULL REFERENCES psl_dw.dim_innings (innings_key),
    over_key               SMALLINT NOT NULL REFERENCES psl_dw.dim_over (over_key),
    date_key               INT      NOT NULL REFERENCES psl_dw.dim_date (date_key),
    venue_key              INT      NOT NULL REFERENCES psl_dw.dim_venue (venue_key),
    batting_team_key       INT      NOT NULL REFERENCES psl_dw.dim_team (team_key),
    bowling_team_key       INT      NOT NULL REFERENCES psl_dw.dim_team (team_key),
    runs_in_over           SMALLINT NOT NULL CHECK (runs_in_over >= 0),
    wickets_in_over        SMALLINT NOT NULL CHECK (wickets_in_over >= 0),
    cumulative_runs        SMALLINT NOT NULL CHECK (cumulative_runs >= 0),
    cumulative_wickets     SMALLINT NOT NULL CHECK (cumulative_wickets >= 0),
    cumulative_legal_balls SMALLINT NOT NULL CHECK (cumulative_legal_balls >= 0),
    PRIMARY KEY (match_key, innings_key, over_key)
);

DROP TABLE IF EXISTS psl_dw.fact_match_player CASCADE;
CREATE TABLE psl_dw.fact_match_player (
    match_key  INT NOT NULL REFERENCES psl_dw.dim_match (match_key),
    team_key   INT NOT NULL REFERENCES psl_dw.dim_team (team_key),
    player_key INT NOT NULL REFERENCES psl_dw.dim_player (player_key),
    date_key   INT NOT NULL REFERENCES psl_dw.dim_date (date_key),
    venue_key  INT NOT NULL REFERENCES psl_dw.dim_venue (venue_key),
    PRIMARY KEY (match_key, team_key, player_key)
);














-- load fact_match_player (our factless fact). This is the smallest fact table, with one row per player in a team’s playing XI.

INSERT INTO psl_dw.fact_match_player (match_key, team_key, player_key, date_key, venue_key)
SELECT dm.match_key, dt.team_key, dp.player_key, dd.date_key, dv.venue_key
FROM psl_staging.stg_match_players p
JOIN psl_staging.stg_matches m     ON m.match_id = p.match_id
JOIN psl_staging.map_venue mv      ON mv.venue_raw = m.venue
JOIN psl_dw.dim_match dm           ON dm.match_id = TRIM(p.match_id)
JOIN psl_dw.dim_team dt            ON dt.team_name = TRIM(p.team)
JOIN psl_dw.dim_player dp          ON dp.player_id = TRIM(p.player_id)
JOIN psl_dw.dim_date dd            ON dd.full_date = m.match_date::DATE
JOIN psl_dw.dim_venue dv           ON dv.venue_name = mv.venue_clean
ON CONFLICT (match_key, team_key, player_key) DO NOTHING;


-- check
SELECT (SELECT COUNT(*) FROM psl_staging.stg_match_players) AS rows_in_staging,
       (SELECT COUNT(*) FROM psl_dw.fact_match_player)      AS rows_in_fact;








-- load fact_over_snapshot (our Periodic table). This is the over-by-over table.
INSERT INTO psl_dw.fact_over_snapshot (match_key, innings_key, over_key, date_key, venue_key,
       batting_team_key, bowling_team_key, runs_in_over, wickets_in_over,
       cumulative_runs, cumulative_wickets, cumulative_legal_balls)
SELECT dm.match_key, di.innings_key, dov.over_key, dd.date_key, dv.venue_key,
       bat.team_key, bowl.team_key,
       s.runs_in_over::SMALLINT, s.wickets_in_over::SMALLINT,
       s.cumulative_runs::SMALLINT, s.cumulative_wickets::SMALLINT, s.cumulative_legal_balls::SMALLINT
FROM psl_staging.stg_over_snapshot s
JOIN psl_staging.stg_matches m   ON m.match_id = s.match_id
JOIN psl_staging.map_venue mv    ON mv.venue_raw = m.venue
JOIN psl_dw.dim_match dm         ON dm.match_id = TRIM(s.match_id)
JOIN psl_dw.dim_innings di       ON di.innings_no = s.innings_no::SMALLINT
JOIN psl_dw.dim_over dov         ON dov.over_no = s.over_no::SMALLINT
JOIN psl_dw.dim_date dd          ON dd.full_date = m.match_date::DATE
JOIN psl_dw.dim_venue dv         ON dv.venue_name = mv.venue_clean
JOIN psl_dw.dim_team bat         ON bat.team_name = TRIM(s.batting_team)
JOIN psl_dw.dim_team bowl        ON bowl.team_name = TRIM(s.bowling_team)
ON CONFLICT (match_key, innings_key, over_key) DO NOTHING;


-- check
SELECT (SELECT COUNT(*) FROM psl_staging.stg_over_snapshot) AS rows_in_staging,
       (SELECT COUNT(*) FROM psl_dw.fact_over_snapshot)     AS rows_in_fact,
       (SELECT SUM(runs_in_over) FROM psl_dw.fact_over_snapshot)          AS runs_in_fact,
       (SELECT SUM(runs_in_over::INT) FROM psl_staging.stg_over_snapshot) AS runs_in_staging;









-- load fact_delivery (our transactional table). This is the main table, with one row per ball (83,799 rows), and it needs the most lookups
-- first a safety check (should return 0, is returning 0) it checks a player isnt repeating in the playing XI
SELECT COUNT(*) AS names_repeated_inside_a_match
FROM (SELECT match_id, player_name FROM psl_staging.stg_match_players
      GROUP BY match_id, player_name HAVING COUNT(*) > 1) x;


-- now load
INSERT INTO psl_dw.fact_delivery (match_key, innings_key, delivery_seq, date_key, venue_key, over_key,
       batting_team_key, bowling_team_key, batter_key, bowler_key, non_striker_key, dismissed_player_key,
       dismissal_type_key, extra_type_key, runs_batter, runs_extras, runs_total, runs_conceded,
       is_legal_ball, balls_faced, wicket_count, is_dot_ball)
SELECT dm.match_key, di.innings_key, d.delivery_seq::SMALLINT, dd.date_key, dv.venue_key, dov.over_key,
       bat.team_key, bowl.team_key,
       pbat.player_key, pbowl.player_key, pns.player_key,
       COALESCE(pout.player_key, -1),
       COALESCE(dt.dismissal_type_key, -1),
       COALESCE(et.extra_type_key, -1),
       d.runs_batter::SMALLINT, d.runs_extras::SMALLINT, d.runs_total::SMALLINT, d.runs_conceded::SMALLINT,
       d.is_legal_ball::SMALLINT, d.balls_faced::SMALLINT, d.wicket_count::SMALLINT,
       CASE WHEN d.is_legal_ball = '1' AND d.runs_total = '0' THEN 1 ELSE 0 END
FROM psl_staging.stg_deliveries d
JOIN psl_staging.stg_matches m          ON m.match_id = d.match_id
JOIN psl_staging.map_venue mv           ON mv.venue_raw = m.venue
JOIN psl_dw.dim_match dm                ON dm.match_id = TRIM(d.match_id)
JOIN psl_dw.dim_innings di              ON di.innings_no = d.innings_no::SMALLINT
JOIN psl_dw.dim_over dov                ON dov.over_no = d.over_no::SMALLINT
JOIN psl_dw.dim_date dd                 ON dd.full_date = m.match_date::DATE
JOIN psl_dw.dim_venue dv                ON dv.venue_name = mv.venue_clean
JOIN psl_dw.dim_team bat                ON bat.team_name = TRIM(d.batting_team)
JOIN psl_dw.dim_team bowl               ON bowl.team_name = TRIM(d.bowling_team)
JOIN psl_staging.stg_match_players sb   ON sb.match_id = d.match_id AND sb.player_name = d.batter
JOIN psl_dw.dim_player pbat             ON pbat.player_id = TRIM(sb.player_id)
JOIN psl_staging.stg_match_players sw   ON sw.match_id = d.match_id AND sw.player_name = d.bowler
JOIN psl_dw.dim_player pbowl            ON pbowl.player_id = TRIM(sw.player_id)
JOIN psl_staging.stg_match_players sn   ON sn.match_id = d.match_id AND sn.player_name = d.non_striker
JOIN psl_dw.dim_player pns              ON pns.player_id = TRIM(sn.player_id)
LEFT JOIN psl_staging.stg_match_players so ON so.match_id = d.match_id AND so.player_name = d.dismissed_player
LEFT JOIN psl_dw.dim_player pout        ON pout.player_id = TRIM(so.player_id)
LEFT JOIN psl_dw.dim_dismissal_type dt  ON dt.dismissal_kind = TRIM(d.dismissal_kind)
LEFT JOIN psl_dw.dim_extra_type et      ON et.extra_type = TRIM(d.extras_type)
ON CONFLICT (match_key, innings_key, delivery_seq) DO NOTHING;




-- check
SELECT (SELECT COUNT(*) FROM psl_staging.stg_deliveries)                AS rows_in_staging,
       (SELECT COUNT(*) FROM psl_dw.fact_delivery)                      AS rows_in_fact,
       (SELECT SUM(runs_total::INT) FROM psl_staging.stg_deliveries)    AS runs_staging,
       (SELECT SUM(runs_total) FROM psl_dw.fact_delivery)               AS runs_fact,
       (SELECT SUM(runs_in_over) FROM psl_dw.fact_over_snapshot)        AS runs_over_snapshot,
       (SELECT SUM(wicket_count::INT) FROM psl_staging.stg_deliveries)  AS wickets_staging,
       (SELECT SUM(wicket_count) FROM psl_dw.fact_delivery)             AS wickets_fact;







